def top_k_table(load_df, pc, k=5):
    k = min(k, load_df.shape[0])
    abs_vals = load_df[pc].abs()
    order = abs_vals.sort_values(ascending=False).head(k).index
    out = pd.DataFrame({
        "Variable": order,
        f"|loading {pc}|": abs_vals.loc[order].values,
        f"loading {pc} (signé)": load_df.loc[order, pc].values,
    })
    return out

