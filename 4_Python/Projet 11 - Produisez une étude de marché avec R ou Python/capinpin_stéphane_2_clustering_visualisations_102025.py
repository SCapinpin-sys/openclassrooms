# --- Helper: tracé d'un cercle des corrélations (PC1–PC2)
def plot_correlation_circle(coords, labels, explained_ratio, title_suffix="", title_color=None):
    x, y = coords[:, 0], coords[:, 1]
    theta = np.linspace(0, 2*np.pi, 400)
    plt.figure()
    plt.plot(np.cos(theta), np.sin(theta))  # cercle unité
    plt.axhline(0, linewidth=0.5)
    plt.axvline(0, linewidth=0.5)
    plt.scatter(x, y)
    for i, name in enumerate(labels):
        plt.arrow(0, 0, x[i], y[i], head_width=0.02, length_includes_head=True)
        plt.text(x[i]*1.07, y[i]*1.07, name, fontsize=8)
    plt.gca().set_aspect('equal', adjustable='box')
    plt.xlim(-1.1, 1.1); plt.ylim(-1.1, 1.1)
    plt.title(
        f"Cercle des corrélations (PC1–PC2){title_suffix}\n"
        f"PC1: {explained_ratio[0]*100:.1f}%  |  PC2: {explained_ratio[1]*100:.1f}%",
        color=title_color
    )
    plt.xlabel("Corrélation avec PC1"); plt.ylabel("Corrélation avec PC2")
    plt.grid(True, linestyle="--", linewidth=0.5)
    plt.show()

