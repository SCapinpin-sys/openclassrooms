# 0) Vérifs rapides : on suppose déjà disponibles -> res, X_pca, explained
assert 'res' in globals() and 'X_pca' in globals() and 'explained' in globals(), \
    "Il faut exécuter l'ACP avant (pour avoir res, X_pca, explained)."

# 1) Choisir le nombre de composantes ACP à garder (~80% var., min=2)
cumvar = np.cumsum(explained)
n_keep = int(np.searchsorted(cumvar, 0.80) + 1)
n_keep = max(2, min(n_keep, X_pca.shape[1]))  # bornes sécurité
scores = pd.DataFrame(X_pca[:, :n_keep], columns=[f"PC{i+1}" for i in range(n_keep)])

