# 2) Helpers pour récupérer des colonnes même si absentes (remplacées par 0)
def col(df, name):
    return df[name] if name in df.columns else 0.0

# Colonnes utiles (en minuscules, comme dans element_norm)
F["imports"]      = col(F, "importations - quantité").fillna(0)
F["exports"]      = col(F, "exportations - quantité").fillna(0)
F["production"]   = col(F, "production").fillna(0)
F["pertes"]       = col(F, "pertes").fillna(0)
F["kg_per_cap"]   = col(F, "disponibilité alimentaire en quantité (kg/personne/an)").fillna(0)
F["kcal_per_cap"] = col(F, "disponibilité alimentaire (kcal/personne/jour)").fillna(0)

# 3) Indicateurs dérivés (robustes aux zéros)
base_supply = F["production"] + F["imports"]
base_supply_safe = base_supply.replace(0, np.nan)
F["import_reliance"] = (F["imports"] / base_supply_safe).fillna(0)   # 0..1 (plus proche de 1 => + dépendant des importations)
F["waste_rate"]      = (F["pertes"] / base_supply_safe).fillna(0)   # optionnel : inefficiences de chaîne

# 4) Score d’attractivité (pondération simple et transparente)
