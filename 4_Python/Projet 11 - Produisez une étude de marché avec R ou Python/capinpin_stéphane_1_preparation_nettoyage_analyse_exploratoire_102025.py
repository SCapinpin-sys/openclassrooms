# 2. Fonction de mapping
def m49_to_region(m49):
    try:
        num = str(int(m49)).zfill(3)
        country = pycountry.countries.get(numeric=num)
        alpha2 = country.alpha_2
        cont_code = pc.country_alpha2_to_continent_code(alpha2)
        mapping = {
            'AF': 'Afrique',    'AS': 'Asie',
            'EU': 'Europe',     'NA': 'Amérique du Nord',
            'OC': 'Océanie',    'SA': 'Amérique du Sud',
            'AN': 'Antarctique'
        }
        return mapping.get(cont_code, 'Inconnu')
    except:
        return 'Inconnu'

