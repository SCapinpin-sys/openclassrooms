# --- Ajout du taux d'évolution global par zone 2014→2018 et CAGR ---
def zone_overall_growth(row):
    v2014 = row.get(2014)
    v2018 = row.get(2018)
    if pd.isna(v2014) or pd.isna(v2018) or v2014 == 0:
        return pd.Series({
            "Changement global 2014→2018 (%)": pd.NA,
            "CAGR annualisé (%)": pd.NA
        })
    cumulative = (v2018 / v2014 - 1) * 100
    years = 2018 - 2014
    cagr = ((v2018 / v2014) ** (1 / years) - 1) * 100
    return pd.Series({
        "Changement global 2014→2018 (%)": round(cumulative, 3),
        "CAGR annualisé (%)": round(cagr, 3)
    })

